//   台 → 臺/台(專案本來就統一用「台」,見 org-match.normalizeOrgName)

/**
 * 逐字吸附簡體字形回繁體。查不到的字原樣通過。
 * @param {*} s
 * @returns {string}
 */
function toTraditional(s) {
  if (s == null) return '';
  let out = '';
  for (const ch of String(s)) out += S2T[ch] || ch;
  return out;
}

module.exports = { S2T, toTraditional };
