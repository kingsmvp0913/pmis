// 「大勇廁所開工報告及相關文件.pdf」:已知殘留缺口,不是遺漏。
// 這份的第 1 頁是直式/表格化排版,OCR 把每個標籤拆成單一字元散落各行
// (如「稱」「名」「工」分屬三行,不會湊出「工程名稱」),整份沒有任何一個
// 標籤命中,唯一可辨識的訊號是退路句「...上項工程於民國115年1月26日正式
// 開工」。這與「敘述句 fallback 可命中開工日」那支測試的 fixture 是完全
// 同型的輸入(純退路句、零標籤),而退路句依規格必須單獨足以放行,因此無法
// 只憑文字內容把兩者分開——勉強加規則去擋這份,代價是連帶擋下所有「只靠
// 退路句」的正常案例。目前這份仍會放行,但因為零標籤命中,除了退路句能填的
// 「契約規定開工日」外其餘欄位全部是 null,不會出現「硬湊出一個看似正確
// 實則錯誤的值」這種最壞情況。
test('真實樣本(已知限制):大勇廁所全靠退路句撐住,目前仍會放行', () => {
  const r = extractFields(mk([
    '臺中市西區大勇國民小學',
    '開工報告',
    '稱',
    '114 學年度辣室所整修工程',
    '名',
    '工程',
    '費',
    '6 , 319 , 000',
    '負責人',
    '徐國志',
    '依據工程契約書規定辦理',
    '、 上項工程於民國 1 1 5 年 1 月 26 日正式開工 。',
  ]));
  expect(r.契約規定開工日).toBe('2026-01-26');
  expect(r.工程名稱).toBeNull();
  expect(r.契約編號).toBeNull();
  expect(r.契約金額).toBeNull();
});

