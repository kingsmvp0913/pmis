// 元長廁所是本輪抓到問題的樣本:工程名稱與契約編號的值都印在標籤「上面」
// 那一列,契約編號的標籤緊接著契約金額的值(無獨立標籤,直接被下一列的
// 金額頂替)。這支測試若抽取邏輯退回上一版(只認同列/下一列),
// 工程名稱會抽到「雲林縣元長鄉元長國民小學」(學校名而非工程名稱)、
// 契約編號會抽到「新台幣 1,091,313 元整」(金額而非契約編號),會變紅。
test('真實樣本(元長廁所):工程名稱不得被學校名稱頂替、契約編號不得被金額頂替', () => {
  const r = extractFields(mk([
    '雲林縣元長鄉元長國民小學',
    '工程開工報告表',
    '元長國小辦理 「 114 一 116 年公立國民中小學老舊廁所整修工程計畫 」',
    '工程名稱',
    '雲林縣元長鄉元長國民小學',
    '工程地點',
    'A1150505',
    '契約編號',
    '新台幣 1 , 091 , 313 元整',
    '丁約總價',
    '本工程於中華民國 115 年 7 月 11 日開工',
    '賜利發土木包工業契約約定工期',
    '120 日曆天',
    '主辦機關',
    '開工日期',
  ]));
  expect(r.工程名稱).toBe('元長國小辦理 「 114 一 116 年公立國民中小學老舊廁所整修工程計畫 」');
  expect(r.契約編號).toBe('A1150505');
  // 這份文件實際上沒有「契約金額」標籤(OCR 把它讀成不在清單裡的「丁約總價」),
  // 抽不到就是 null,不能硬湊——上面已經證明鄰近的金額字串不會被契約編號收走,
  // 這裡再次確認它也不會被契約金額自己收走(型別對但沒標籤仍是找不到)。
  expect(r.契約金額).toBeNull();
  expect(r.契約工期).toEqual({ 天數: 120, 基準: '日曆天' });
});

// 「學校」欄位(主辦機關)抽到「提報單位」四個字,是本輪回報最直接的證據:
// 舊版 `isAnyLabel` 只認自己 9 個欄位的標籤,「提報單位」沒列進去,下一列
// 就被當成值收下。這支測試專門守住「值不得是另一個標籤」這條:退回舊版邏輯,
