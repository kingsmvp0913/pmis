// ===========================================================================
// 型別把關:座標找對格子 ≠ 格子裡的字是好的
// ===========================================================================

// 橋頭國小署名欄的尾字被印章蓋掉,兩個解析度都只讀到「( 雲林縣麥寮鄉橋頭國民小」。
// 「學校」在 kickoff-compare 是 hard 級,收下這個殘缺值會讓比對判 diff → 假硬錯
// → 擋住歸檔;判成讀不到則是 missing,不進 hardErrors,不擋人。
test('校名尾字被蓋掉時判讀不到,不得產生假硬錯', () => {
  const r = extractFields(mk([
    [1985, 2279, 253, 63, '主辦機關'],
    [1765, 2373, 721, 63, '( 雲林縣麥寮鄉橋頭國民小'],
  ]));
  expect(r.主辦機關).toBeNull();
});

// 新光國小的契約編號欄空著,右側最近的是金額。收下就會讓「契約編號」變成
// 一串金額數字,而它在比對層同樣是 hard 級。
test('契約編號不得收下金額', () => {
  const r = extractFields(mk([
    [337, 955, 261, 60, '契約編號'],
    [874, 955, 266, 61, '1 , 640 , 000'],
  ]));
  expect(r.契約編號).toBeNull();
});

// 署名欄的值寫成「(校名)」,而尾括號常被印章吃掉,成對規則就不成立。
test('值的單邊括號要清掉', () => {
  const r = extractFields(mk([
    [1757, 1872, 236, 56, '主辦機關'],
    [1520, 1961, 718, 64, '( 雲林縣元長鄉元長國民小學'],
  ]));
  expect(r.主辦機關).toBe('雲林縣元長鄉元長國民小學');
});

// ===========================================================================
// 敘述句退路
// ===========================================================================

// 退路的觸發條件必須是「解不出天數」而非「標籤沒命中」。標籤命中、但那一格
// 被 OCR 毀掉(豐榮的工期讀成「一』一一」)時,一個非 null 的垃圾字串會把退路
// 整個擋掉——原型第一版就是這樣讓工期從 15 份掉到 8 份。
test('標籤命中但值解不出天數時仍要走敘述句退路', () => {
  const r = extractFields(mk([
    [355, 1548, 266, 59, '契約規定工期'],
    [800, 1548, 200, 59, '一』一一'],
    [344, 1626, 1199, 52, '本工程機關通知日起 90 日曆天竣工'],
  ]));
  expect(r.契約工期).toEqual({ 天數: 90, 基準: '日曆天' });
});

// 幾乎每份都有這句,是標籤抓不到時的唯一退路。
test('敘述句 fallback 可命中開工日', () => {
  const r = extractFields(mk([
    [344, 1626, 1199, 52, '本工程定於中華民國115年6月16日正式開工'],
  ]));
  expect(r.契約規定開工日).toBe('2026-06-16');
});

// 標籤命中時不得被 fallback 蓋掉
test('標籤優先於敘述句 fallback', () => {
  const r = extractFields(mk([
    [283, 1586, 235, 59, '契約規定開工日'],
    [748, 1586, 467, 59, '115/3/18'],
    [344, 1626, 1199, 52, '本工程定於中華民國115年6月16日正式開工'],
  ]));
  expect(r.契約規定開工日).toBe('2026-03-18');
});

// 元長廁所的「契約總價」被 OCR 讀成「丁約總價」,標籤路徑必然落空,
// 但值「新台幣 1,091,313 元整」好端端在旁邊。
// **不**改用模糊比對標籤:「竣工日期」與「開工日期」只差一個字,放寬字元容差
// 會把這兩欄配錯,比抽不到嚴重得多。
test('金額標籤被 OCR 毀掉時走新台幣退路', () => {
  const r = extractFields(mk([
    [613, 950, 572, 60, '新台幣 1 , 091 , 313 元整'],
    [289, 953, 213, 57, '丁約總價'],
    [263, 649, 237, 58, '工程名稱'],
    [665, 626, 1690, 73, '元長國小老舊廁所整修工程'],
  ]));
  expect(r.契約金額).toBe(1091313);
});

