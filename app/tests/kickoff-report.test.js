// 表單的工期欄是「（80）日曆天 /（  ）工作天」,**括號讓 OCR 把數字與基準詞斷成
// 兩個框、而且分屬不同行**,所以行層的 durationSentenceFallback 永遠拼不出
// 「80日曆天」。座標層它們是水平相鄰的(80 右緣 2456、日曆天左緣 2481)。
test('括號把工期數字與基準詞斷開時,由座標層拼回來(文安)', () => {
  const r = extractFields(mk([
    [2338, 2270, 118, 68, '80'],
    [2481, 2278, 276, 68, '日曆天'],
    [2453, 2385, 231, 68, '工作天'],
    [1802, 2501, 195, 68, '工期'],
    // 守門要求整份看得出是開工報告表,只有「工期」一個標籤會被整份擋下
    [413, 814, 333, 68, '工程名稱'],
    [1491, 814, 920, 68, '某某國小廁所整修工程'],
  ], 3400));
  expect(r.契約工期).toEqual({ 天數: 80, 基準: '日曆天' });
});

// 明禮那份的數字在「工作天」旁邊,不是「日曆天」——基準判錯會讓日曆天的案子
// 被當工作天驗(或反之),產生一個必然的假硬錯。
test('數字在哪個基準詞旁邊就算哪一種(明禮是工作天)', () => {
  const r = extractFields(mk([
    [2573, 1882, 221, 68, '日曆天'],
    [2448, 1990, 140, 68, '160'],
    [2553, 1997, 353, 68, '） 工作天'],
    [1889, 2055, 198, 68, '工期'],
    [413, 814, 333, 68, '工程名稱'],
    [1491, 814, 920, 68, '某某國小廁所整修工程'],
  ], 3400));
  expect(r.契約工期).toEqual({ 天數: 160, 基準: '工作天' });
});

// 兩個基準詞都帶數字時**不猜**:猜錯會產生必然的假硬錯,而承辦人本來就知道
